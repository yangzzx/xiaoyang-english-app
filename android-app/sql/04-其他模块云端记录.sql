-- v4：其他学习模块的个人记录；不修改 day32_* 表和函数。
create table if not exists public.study_records (
 user_id uuid not null references auth.users(id) on delete cascade,
 module text not null check (module in ('phon','phonics','mother','core','spell','courses','grammar','papers','essay','plan')),
 item_key text not null check (length(item_key) between 1 and 240),
 data jsonb not null default '{}'::jsonb check (jsonb_typeof(data)='object' and octet_length(data::text)<=150000),
 completed_at timestamptz,
 updated_at timestamptz not null default now(),
 primary key(user_id,module,item_key)
);
create table if not exists public.study_reviews (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 module text not null,
 item_key text not null,
 scheduled_for date not null,
 completed_at timestamptz,
 result text check(result in ('remembered','fuzzy','forgotten')),
 unique(user_id,module,item_key,scheduled_for),
 foreign key(user_id,module,item_key) references public.study_records(user_id,module,item_key) on delete cascade
);
create table if not exists public.study_answers (
 user_id uuid not null references auth.users(id) on delete cascade,
 attempt_id uuid not null,
 module text not null check(module='spell'),
 item_key text not null,
 correct boolean not null,
 answered_at timestamptz not null default now(),
 primary key(user_id,attempt_id)
);
create index if not exists study_reviews_due_idx on public.study_reviews(user_id,scheduled_for) where completed_at is null;
alter table public.study_records enable row level security;
alter table public.study_reviews enable row level security;
alter table public.study_answers enable row level security;
drop policy if exists own_records on public.study_records;
create policy own_records on public.study_records for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
drop policy if exists own_reviews on public.study_reviews;
create policy own_reviews on public.study_reviews for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
drop policy if exists own_answers on public.study_answers;
create policy own_answers on public.study_answers for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
grant select,insert,update on public.study_records,public.study_reviews,public.study_answers to authenticated;
grant usage,select on sequence public.study_reviews_id_seq to authenticated;

create or replace function public.study_save(p_module text,p_key text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare u uuid:=auth.uid(); r public.study_records;
begin
 if u is null then raise exception 'authentication required'; end if;
 if p_module is null or p_module not in ('phon','phonics','mother','core','spell','courses','grammar','papers','essay','plan') or p_key is null or length(p_key) not between 1 and 240 or p_data is null or jsonb_typeof(p_data)<>'object' or octet_length(p_data::text)>150000 then raise exception 'invalid record'; end if;
 insert into public.study_records(user_id,module,item_key,data) values(u,p_module,p_key,p_data)
 on conflict(user_id,module,item_key) do update set data=study_records.data||excluded.data,updated_at=now() returning * into r;
 return to_jsonb(r);
end $$;

create or replace function public.study_complete(p_module text,p_key text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare u uuid:=auth.uid(); r public.study_records; was_done boolean; d date:=(now() at time zone 'Asia/Shanghai')::date;
begin
 if u is null then raise exception 'authentication required'; end if;
 if p_module='plan' then raise exception 'plan preferences do not create reviews'; end if;
 perform pg_advisory_xact_lock(hashtextextended(u::text||':'||p_module||':'||p_key,0));
 perform public.study_save(p_module,p_key,p_data);
 select * into r from public.study_records where user_id=u and module=p_module and item_key=p_key for update;
 was_done:=r.completed_at is not null;
 if not was_done then
  update public.study_records set completed_at=now(),updated_at=now() where user_id=u and module=p_module and item_key=p_key returning * into r;
  insert into public.study_reviews(user_id,module,item_key,scheduled_for)
   select u,p_module,p_key,d+n from unnest(array[1,3,7,14]) n on conflict do nothing;
 end if;
 return jsonb_build_object('record',to_jsonb(r),'already_completed',was_done);
end $$;

create or replace function public.study_grade(p_review bigint,p_result text)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare u uuid:=auth.uid();r public.study_reviews;d date:=(now() at time zone 'Asia/Shanghai')::date;
begin
 if u is null then raise exception 'authentication required'; end if;
 if p_result is null or p_result not in ('remembered','fuzzy','forgotten') then raise exception 'invalid grade';end if;
 select * into r from public.study_reviews where user_id=u and id=p_review for update;
 if not found then raise exception 'review not found';end if;
 if r.completed_at is not null then return jsonb_build_object('already_completed',true);end if;
 if r.scheduled_for>d then raise exception 'review not due';end if;
 update public.study_reviews set completed_at=now(),result=p_result where id=r.id and user_id=u;
 if p_result<>'remembered' then
  insert into public.study_reviews(user_id,module,item_key,scheduled_for) values(u,r.module,r.item_key,d+1) on conflict do nothing;
 end if;
 return jsonb_build_object('already_completed',false,'extra_review_tomorrow',p_result<>'remembered');
end $$;

create or replace function public.study_grade_many(p_reviews bigint[],p_result text)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare
 u uuid:=auth.uid();r public.study_reviews;review_id bigint;d date:=(now() at time zone 'Asia/Shanghai')::date;
 processed integer:=0;extra boolean:=false;
begin
 if u is null then raise exception 'authentication required'; end if;
 if p_reviews is null or cardinality(p_reviews) not between 1 and 200 then raise exception 'invalid reviews'; end if;
 if p_result is null or p_result not in ('remembered','fuzzy','forgotten') then raise exception 'invalid grade'; end if;
 perform pg_advisory_xact_lock(hashtextextended(u::text||':review-many',0));
 for review_id in select distinct unnest(p_reviews) loop
  select * into r from public.study_reviews where user_id=u and id=review_id for update;
  if not found then raise exception 'review not found'; end if;
  if r.completed_at is not null then continue; end if;
  if r.scheduled_for>d then raise exception 'review not due'; end if;
  update public.study_reviews set completed_at=now(),result=p_result where id=r.id and user_id=u;
  processed:=processed+1;
  if p_result<>'remembered' then
   insert into public.study_reviews(user_id,module,item_key,scheduled_for) values(u,r.module,r.item_key,d+1) on conflict do nothing;
   extra:=true;
  end if;
 end loop;
 return jsonb_build_object('saved',processed>0,'processed',processed,'extra_review_tomorrow',extra,'already_completed',processed=0);
end $$;

create or replace function public.study_spell_answer(p_key text,p_correct boolean,p_attempt uuid,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare u uuid:=auth.uid();r public.study_records;streak integer;first_answer boolean;d date:=(now() at time zone 'Asia/Shanghai')::date;inserted integer;
begin
 if u is null then raise exception 'authentication required'; end if;
 if p_correct is null or p_attempt is null then raise exception 'invalid answer';end if;
 perform pg_advisory_xact_lock(hashtextextended(u::text||':spell:'||p_key,0));
 insert into public.study_answers(user_id,attempt_id,module,item_key,correct) values(u,p_attempt,'spell',p_key,p_correct) on conflict do nothing;
 get diagnostics inserted=row_count;
 if inserted=0 then return jsonb_build_object('duplicate',true);end if;
 perform public.study_save('spell',p_key,p_data);
 select * into r from public.study_records where user_id=u and module='spell' and item_key=p_key for update;
 first_answer:=not(r.data?'answer_count');
 streak:=case when p_correct then coalesce((r.data->>'streak')::integer,0)+1 else 0 end;
 update public.study_records set data=data||jsonb_build_object('streak',streak,'answer_count',coalesce((data->>'answer_count')::integer,0)+1,'wrong_count',coalesce((data->>'wrong_count')::integer,0)+case when p_correct then 0 else 1 end,'last_correct',p_correct,'last_answered_at',now(),'mastered',streak>=2),completed_at=case when streak>=2 then coalesce(completed_at,now()) else null end,updated_at=now() where user_id=u and module='spell' and item_key=p_key returning * into r;
 if first_answer then
  insert into public.study_reviews(user_id,module,item_key,scheduled_for) select u,'spell',p_key,d+n from unnest(array[1,3,7,14]) n on conflict do nothing;
 elsif not p_correct then
  insert into public.study_reviews(user_id,module,item_key,scheduled_for) values(u,'spell',p_key,d+1) on conflict do nothing;
 end if;
 return jsonb_build_object('duplicate',false,'record',to_jsonb(r));
end $$;

-- 旧进度导入为单个事务，明确核对后才调用；已存在的完成日期保留。
create or replace function public.study_import(p_module text,p_keys text[])
returns jsonb language plpgsql security invoker set search_path=public as $$
declare k text;n integer:=0;
begin
 if auth.uid() is null then raise exception 'authentication required';end if;
 if p_keys is null or cardinality(p_keys) not between 1 and 2000 or array_position(p_keys,null) is not null then raise exception 'invalid import';end if;
 foreach k in array p_keys loop
  if length(k) not between 1 and 240 then raise exception 'invalid key';end if;
 end loop;
 for k in select distinct unnest(p_keys) loop
  perform public.study_complete(p_module,k,jsonb_build_object('imported',true));n:=n+1;
 end loop;
 return jsonb_build_object('imported',n);
end $$;
revoke all on function public.study_save(text,text,jsonb), public.study_complete(text,text,jsonb), public.study_grade(bigint,text), public.study_grade_many(bigint[],text),public.study_spell_answer(text,boolean,uuid,jsonb),public.study_import(text,text[]) from public,anon;
grant execute on function public.study_save(text,text,jsonb), public.study_complete(text,text,jsonb), public.study_grade(bigint,text),public.study_grade_many(bigint[],text),public.study_spell_answer(text,boolean,uuid,jsonb),public.study_import(text,text[]) to authenticated;

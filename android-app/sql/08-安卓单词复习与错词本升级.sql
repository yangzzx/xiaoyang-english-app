-- Android word-level review queue and personal wrong-word notebook.
-- Existing course and review rows are not modified.

create table if not exists public.study_word_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  module text not null check (module in ('root','core','mother','phon','phonics')),
  parent_key text not null,
  word_key text not null,
  english text not null,
  chinese text not null,
  pattern text,
  example text,
  scheduled_for date not null,
  stage integer not null default 0 check (stage between 0 and 6),
  active boolean not null default true,
  completed_at timestamptz,
  result text check (result in ('remembered','fuzzy','forgotten')),
  created_at timestamptz not null default now()
);

create unique index if not exists study_word_reviews_one_active
  on public.study_word_reviews(user_id,module,word_key)
  where active and completed_at is null;
create index if not exists study_word_reviews_due_idx
  on public.study_word_reviews(user_id,scheduled_for)
  where active and completed_at is null;
alter table public.study_word_reviews enable row level security;
drop policy if exists study_word_reviews_own_rows on public.study_word_reviews;
create policy study_word_reviews_own_rows on public.study_word_reviews
  for all to authenticated using ((select auth.uid())=user_id)
  with check ((select auth.uid())=user_id);
grant select,insert,update on public.study_word_reviews to authenticated;
grant usage,select on sequence public.study_word_reviews_id_seq to authenticated;

create or replace function public.study_word_sync(p_items jsonb)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare
  u uuid:=auth.uid(); d date:=(now() at time zone 'Asia/Shanghai')::date;
  item jsonb; inserted_count integer:=0; parent_module text; parent_key text;
  word_module text; word_key text; en text; zh text;
begin
  if u is null then raise exception 'authentication required'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)>3000 then raise exception 'invalid review items'; end if;
  for item in select value from jsonb_array_elements(p_items) loop
    word_module:=item->>'module'; parent_module:=item->>'parent_module';
    parent_key:=item->>'parent_key'; word_key:=item->>'word_key';
    en:=left(trim(item->>'english'),160); zh:=left(trim(item->>'chinese'),500);
    if word_module not in ('root','core','mother','phon','phonics') or coalesce(en,'')='' or coalesce(zh,'')='' then continue; end if;
    if parent_module='root' then
      if not exists(select 1 from public.day32_lessons where user_id=u and day_no=parent_key::integer and status='completed') then continue; end if;
    else
      if not exists(select 1 from public.study_records where user_id=u and module=parent_module and item_key=parent_key and completed_at is not null) then continue; end if;
    end if;
    insert into public.study_word_reviews(user_id,module,parent_key,word_key,english,chinese,pattern,example,scheduled_for)
      values(u,word_module,parent_key,word_key,en,zh,left(item->>'pattern',240),left(item->>'example',500),d+1+mod(mod(hashtextextended(u::text||':'||word_module||':'||word_key,0),7)+7,7)::integer)
      on conflict do nothing;
    if found then inserted_count:=inserted_count+1; end if;
  end loop;
  return jsonb_build_object('inserted',inserted_count);
end $$;

create or replace function public.study_word_grade(p_review bigint,p_result text)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare
  u uuid:=auth.uid(); r public.study_word_reviews; d date:=(now() at time zone 'Asia/Shanghai')::date;
  intervals integer[]:=array[1,3,7,15,30,60,90]; next_stage integer;
begin
  if u is null then raise exception 'authentication required'; end if;
  if p_result not in ('remembered','fuzzy','forgotten') then raise exception 'invalid result'; end if;
  select * into r from public.study_word_reviews where id=p_review and user_id=u and active and completed_at is null for update;
  if not found then raise exception 'review item unavailable'; end if;
  next_stage:=case p_result when 'remembered' then least(6,r.stage+1) when 'fuzzy' then greatest(0,r.stage-1) else 0 end;
  update public.study_word_reviews set active=false,completed_at=now(),result=p_result where id=r.id;
  insert into public.study_word_reviews(user_id,module,parent_key,word_key,english,chinese,pattern,example,scheduled_for,stage)
    values(u,r.module,r.parent_key,r.word_key,r.english,r.chinese,r.pattern,r.example,d+intervals[next_stage+1],next_stage);
  return jsonb_build_object('saved',true,'stage',next_stage,'scheduled_for',d+intervals[next_stage+1]);
end $$;

create table if not exists public.study_wrong_words (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  english text not null check (length(trim(english)) between 1 and 160),
  chinese text not null check (length(trim(chinese)) between 1 and 500),
  streak integer not null default 0 check (streak between 0 and 2),
  wrong_count integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.study_wrong_words drop constraint if exists study_wrong_words_streak_check;
alter table public.study_wrong_words add constraint study_wrong_words_streak_check check (streak between 0 and 10);
create unique index if not exists study_wrong_words_user_english
  on public.study_wrong_words(user_id,lower(trim(english)));
alter table public.study_wrong_words enable row level security;
drop policy if exists study_wrong_words_own_rows on public.study_wrong_words;
create policy study_wrong_words_own_rows on public.study_wrong_words
  for all to authenticated using ((select auth.uid())=user_id)
  with check ((select auth.uid())=user_id);
grant select,insert,update,delete on public.study_wrong_words to authenticated;
grant usage,select on sequence public.study_wrong_words_id_seq to authenticated;

revoke all on function public.study_word_sync(jsonb),public.study_word_grade(bigint,text) from public,anon;
grant execute on function public.study_word_sync(jsonb),public.study_word_grade(bigint,text) to authenticated;

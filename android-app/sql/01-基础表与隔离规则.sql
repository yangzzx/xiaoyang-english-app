create table if not exists public.day32_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  completed_days smallint not null default 0 check (completed_days between 0 and 32),
  current_day smallint not null default 1 check (current_day between 1 and 32),
  streak_days integer not null default 0,
  last_completed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.day32_lessons (
  user_id uuid not null references auth.users(id) on delete cascade,
  day_no smallint not null check (day_no between 1 and 32),
  status text not null default 'locked' check (status in ('locked','available','completed')),
  completed_at timestamptz,
  next_review_at timestamptz,
  review_stage smallint not null default 0 check (review_stage between 0 and 4),
  primary key (user_id, day_no)
);

create table if not exists public.day32_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  day_no smallint not null check (day_no between 1 and 32),
  scheduled_for date not null,
  result text check (result in ('remembered','fuzzy','forgotten')),
  completed_at timestamptz,
  unique (user_id, day_no, scheduled_for)
);

alter table public.day32_progress enable row level security;
alter table public.day32_lessons enable row level security;
alter table public.day32_reviews enable row level security;

drop policy if exists "day32_progress own rows" on public.day32_progress;
create policy "day32_progress own rows" on public.day32_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "day32_lessons own rows" on public.day32_lessons;
create policy "day32_lessons own rows" on public.day32_lessons for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "day32_reviews own rows" on public.day32_reviews;
create policy "day32_reviews own rows" on public.day32_reviews for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.touch_day32_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists day32_progress_touch on public.day32_progress;
create trigger day32_progress_touch before update on public.day32_progress for each row execute function public.touch_day32_updated_at();
